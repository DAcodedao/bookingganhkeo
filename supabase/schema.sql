-- 6.1 Ràng buộc còn lại trên 2 bảng booking / khách lẻ
select conrelid::regclass::text as bang,
       conname as rang_buoc,
       pg_get_constraintdef(oid) as dinh_nghia
from pg_constraint
where conrelid in ('public.bookings'::regclass, 'public.walk_ins'::regclass)
  and contype = 'c'
order by 1, 2;

-- 6.2 Không còn trạng thái lạ ngoài 4 giá trị giao diện dùng
select 'bookings' as bang, status, count(*) as so_dong
from public.bookings
group by status
union all
select 'walk_ins', status, count(*)
from public.walk_ins
group by status
order by 1, 2;
