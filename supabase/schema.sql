create table if not exists public.bookings (
  id text primary key,
  name text not null,
  phone text not null,
  guests integer not null default 1 check (guests > 0),
  date date not null,
  time text not null,
  table_ids text[] not null default '{}',
  deposit numeric(12, 2) not null default 0 check (deposit >= 0),
  note text not null default '',
  status text not null default 'confirmed',
  check_in timestamptz,
  completed_at timestamptz,
  cancelled_at timestamptz,
  created timestamptz not null default now(),
  constraint bookings_status_check
    check (status in ('confirmed', 'arrived', 'completed', 'cancelled'))
);

create index if not exists bookings_date_time_idx
  on public.bookings (date, time);

create table if not exists public.walk_ins (
  id text primary key,
  customer_name text not null default '',
  date date not null,
  time text not null,
  table_ids text[] not null default '{}',
  guests integer not null check (guests > 0),
  status text not null default 'arrived',
  check_in timestamptz not null default now(),
  completed_at timestamptz,
  staff_name text not null,
  constraint walk_ins_status_check
    check (status in ('arrived', 'completed', 'cancelled'))
);

create index if not exists walk_ins_date_time_idx
  on public.walk_ins (date, time);

create table if not exists public.booking_history (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  staff_name text not null,
  action text not null,
  subject text not null
);

create table if not exists public.table_groups (
  id uuid primary key default gen_random_uuid(),
  table_ids text[] not null,
  created_at timestamptz not null default now(),
  check (cardinality(table_ids) >= 2)
);

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('manager', 'employee')),
  created_at timestamptz not null default now()
);

